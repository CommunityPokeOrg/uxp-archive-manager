#!/usr/bin/env python3
"""Generate tests/fixtures.js — deterministic archive fixtures embedded as
base64 so the JS test harness needs nothing but a JS engine.

Run:  python3 tests/gen_fixtures.py
"""
import base64, io, os, tarfile, zipfile, zlib, gzip

OUT = os.path.join(os.path.dirname(__file__), "fixtures.js")
fx = {}


def make_zip(entries, compression=zipfile.ZIP_DEFLATED):
    """entries: list of (name, bytes or None-for-dir)."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression) as z:
        for name, data in entries:
            zi = zipfile.ZipInfo(name)
            zi.compress_type = compression
            zi.external_attr = 0o644 << 16
            if data is None:
                zi.external_attr |= 0x10
                z.writestr(zi, b"")
            else:
                z.writestr(zi, data)
    return buf.getvalue()


def make_tar(members):
    """members: list of dicts {name, data|None, type, linkname}."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.PAX_FORMAT) as t:
        for m in members:
            data = m.get("data")
            ti = tarfile.TarInfo(m["name"])
            ti.mtime = m.get("mtime", 1600000000)
            if m.get("type") == "dir":
                ti.type = tarfile.DIRTYPE
                ti.mode = 0o755
                t.addfile(ti)
            elif m.get("type") == "symlink":
                ti.type = tarfile.SYMTYPE
                ti.linkname = m["linkname"]
                t.addfile(ti)
            elif m.get("type") == "hardlink":
                ti.type = tarfile.LNKTYPE
                ti.linkname = m["linkname"]
                t.addfile(ti)
            else:
                ti.size = len(data)
                ti.mode = 0o644
                t.addfile(ti, io.BytesIO(data))
    return buf.getvalue()


def raw_deflate(data, level=6, strategy=0):
    co = zlib.compressobj(level, zlib.DEFLATED, -15, 9, strategy)
    return co.compress(data) + co.flush()


# ---- ZIP fixtures ----
fx["zip_deflate"] = make_zip([
    ("dir/", None),
    ("dir/hello.txt", b"hello world\n" * 20),
    ("notes/read me.md", b"# archive manager\n" * 5),
])
fx["zip_stored"] = make_zip([
    ("plain.bin", bytes(range(256)) * 4),
], compression=zipfile.ZIP_STORED)
fx["zip_slip"] = make_zip([
    ("ok/inner.txt", b"fine"),
    ("../../evil.txt", b"zip-slip"),
    ("/abs/rooted.txt", b"absolute"),
    ("C:\\win\\evil.bat", b"drive"),
    ("..\\..\\evil2.txt", b"backslash-slip"),
    ("dir/../sibling.txt", b"inner-traversal"),
])

# ---- TAR fixtures ----
fx["tar_basic"] = make_tar([
    {"name": "top/", "type": "dir"},
    {"name": "top/a.txt", "data": b"alpha"},
    {"name": "b" * 120 + ".txt", "data": b"long pax name"},  # pax path record
    {"name": "top/link", "type": "symlink", "linkname": "a.txt"},
    {"name": "escape", "type": "symlink", "linkname": "../../../etc/passwd"},
    {"name": "hard", "type": "hardlink", "linkname": "top/a.txt"},
])
fx["tar_evil"] = make_tar([
    {"name": "../evil", "data": b"x"},
    {"name": "fine.txt", "data": b"y"},
])
fx["tar_gz"] = gzip.compress(fx["tar_basic"])

# ---- raw deflate vectors (wbits=-15) ----
fx["infl_stored"] = raw_deflate(b"stored block " * 3, level=0)
fx["infl_fixed"] = raw_deflate(b"fixed huffman " * 10, level=1)
fx["infl_dynamic"] = raw_deflate(
    (b"the quick brown fox jumps over the lazy dog. " * 400), level=9)
fx["infl_big"] = raw_deflate(bytes(range(256)) * 300, level=6)

with open(OUT, "w") as f:
    f.write("/* Generated by gen_fixtures.py — deterministic fixtures. */\n")
    f.write('"use strict";\nvar FIXTURES = {\n')
    for k, v in sorted(fx.items()):
        f.write('  "%s": "%s",\n' % (k, base64.b64encode(v).decode()))
    f.write("};\n")

# expected plaintexts for inflate vectors
exp = {
    "infl_stored": b"stored block " * 3,
    "infl_fixed": b"fixed huffman " * 10,
    "infl_dynamic": b"the quick brown fox jumps over the lazy dog. " * 400,
    "infl_big": bytes(range(256)) * 300,
}
with open(OUT, "a") as f:
    f.write("var FIXTURE_EXPECT = {\n")
    for k, v in sorted(exp.items()):
        f.write('  "%s": "%s",\n' % (k, base64.b64encode(v).decode()))
    f.write("};\n")

print("wrote", OUT, "with", len(fx), "fixtures")
